
USE ROLE ACCOUNTADMIN;

USE ROLE USERADMIN;

-- Put the dbt role under SYSADMIN, so ACCOUNTADMIN inherits its privileges
GRANT ROLE SWEDAVIA_DBT_ROLE TO ROLE SYSADMIN;

-- 1. The dbt role can use the warehouse and the database
GRANT USAGE ON WAREHOUSE SWEDAVIA_WH TO ROLE SWEDAVIA_DBT_ROLE;
GRANT USAGE ON DATABASE FLIGHT_DB TO ROLE SWEDAVIA_DBT_ROLE;

-- 2. The dbt role can read the raw data loaded by dlt
GRANT USAGE ON SCHEMA FLIGHT_DB.STAGING TO ROLE SWEDAVIA_DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA FLIGHT_DB.STAGING TO ROLE SWEDAVIA_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FLIGHT_DB.STAGING TO ROLE SWEDAVIA_DBT_ROLE;

-- 3. The dbt role can create its own schemas and tables
GRANT CREATE SCHEMA ON DATABASE FLIGHT_DB TO ROLE SWEDAVIA_DBT_ROLE;

-- 4. The dbt user can use the dbt role
GRANT ROLE SWEDAVIA_DBT_ROLE TO USER SWEDAVIA_TRANSFORMER;

SHOW GRANTS TO ROLE SWEDAVIA_DBT_ROLE;
