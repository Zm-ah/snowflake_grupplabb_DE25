-- Create a dedicated role for the dlt pipeline
USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS SWEDAVIA_DLT_ROLE;

-- Grant permissions to the role
USE ROLE ACCOUNTADMIN;

GRANT USAGE ON WAREHOUSE SWEDAVIA_WH
TO ROLE SWEDAVIA_DLT_ROLE;

GRANT USAGE ON DATABASE FLIGHT_DB
TO ROLE SWEDAVIA_DLT_ROLE;

GRANT USAGE ON SCHEMA FLIGHT_DB.STAGING
TO ROLE SWEDAVIA_DLT_ROLE;

GRANT CREATE TABLE ON SCHEMA FLIGHT_DB.STAGING
TO ROLE SWEDAVIA_DLT_ROLE;

GRANT SELECT, INSERT, UPDATE, DELETE
ON ALL TABLES IN SCHEMA FLIGHT_DB.STAGING
TO ROLE SWEDAVIA_DLT_ROLE;

GRANT SELECT, INSERT, UPDATE, DELETE
ON FUTURE TABLES IN SCHEMA FLIGHT_DB.STAGING
TO ROLE SWEDAVIA_DLT_ROLE;

-- Verify role grants
SHOW GRANTS TO ROLE SWEDAVIA_DLT_ROLE;

USE ROLE ACCOUNTADMIN;

GRANT CREATE SCHEMA ON DATABASE FLIGHT_DB TO ROLE SWEDAVIA_DLT_ROLE;



-- Reader role: can read, cannot write
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS SWEDAVIA_READER_ROLE;

USE ROLE ACCOUNTADMIN;
GRANT USAGE ON WAREHOUSE SWEDAVIA_WH TO ROLE SWEDAVIA_READER_ROLE;
GRANT USAGE ON DATABASE FLIGHT_DB TO ROLE SWEDAVIA_READER_ROLE;
GRANT USAGE ON SCHEMA FLIGHT_DB.STAGING TO ROLE SWEDAVIA_READER_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA FLIGHT_DB.STAGING TO ROLE SWEDAVIA_READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FLIGHT_DB.STAGING TO ROLE SWEDAVIA_READER_ROLE;

USE ROLE SECURITYADMIN;
GRANT ROLE SWEDAVIA_READER_ROLE TO ROLE SYSADMIN;

-- Who has which role
USE ROLE USERADMIN;
GRANT ROLE SWEDAVIA_READER_ROLE TO USER ZINEBMOUHIB;
GRANT ROLE SWEDAVIA_READER_ROLE TO USER GHALIA;
GRANT ROLE SWEDAVIA_READER_ROLE TO USER KRISTIAN;
GRANT ROLE SWEDAVIA_READER_ROLE TO USER YOUSIF;

ALTER USER GHALIA SET DEFAULT_ROLE = SWEDAVIA_READER_ROLE;
ALTER USER KRISTIAN SET DEFAULT_ROLE = SWEDAVIA_READER_ROLE;
ALTER USER YOUSIF SET DEFAULT_ROLE = SWEDAVIA_READER_ROLE;

REVOKE ROLE SWEDAVIA_DLT_ROLE FROM USER KRISTIAN;
REVOKE ROLE SWEDAVIA_DLT_ROLE FROM USER YOUSIF;

SHOW GRANTS OF ROLE SWEDAVIA_READER_ROLE;
